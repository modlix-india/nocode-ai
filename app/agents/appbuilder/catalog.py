"""Component catalog — fetches and caches component metadata.

The catalog is generated by nocode-ui's CI pipeline from component
source files (*Properties.ts, *StyleProperties.ts) and deployed
to CDN as component-catalog.json.

nocode-ai fetches this catalog at startup and makes it available
to the agent's system prompt, so the agent knows valid properties
per component type.

For development (when no CDN catalog is available), falls back to
a minimal built-in catalog derived from the aicontext docs.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any

import httpx

logger = logging.getLogger(__name__)

_CATALOG_FILE_NAME = "component-catalog.json"


def _default_local_catalog_path() -> Path | None:
    """`<repo>/nocode-ui/ui-app/client/dist/component-catalog.json`, if present.

    Resolved relative to this file so a dev box picks up the real generated
    catalog with no configuration. Absent in prod, where only the CDN copy
    exists, and that is the intended outcome there.
    """
    # app/agents/appbuilder/catalog.py → appbuilder → agents → app → <root>
    install_root = Path(__file__).resolve().parents[3]
    candidate = (
        install_root.parent / "nocode-ui" / "ui-app" / "client" / "dist" / _CATALOG_FILE_NAME
    )
    return candidate if candidate.exists() else None


def _resolve_local_catalog(configured: str) -> Path | None:
    """A local catalog file from a configured path, or the default location.

    Accepts the nocode-ui client dir, its `dist/` dir, or the JSON file itself,
    because all three are things somebody reasonably types.
    """
    if not configured:
        return _default_local_catalog_path()
    base = Path(configured).expanduser()
    if base.is_file() and base.name == _CATALOG_FILE_NAME:
        return base
    for tail in (f"dist/{_CATALOG_FILE_NAME}", _CATALOG_FILE_NAME):
        candidate = base / tail
        if candidate.exists():
            return candidate
    return None


class ComponentCatalog:
    """Fetches and caches the component catalog."""

    def __init__(self, catalog_url: str = "", local_path: str = "") -> None:
        self.catalog_url = catalog_url
        self.local_path = local_path
        self._catalog: dict[str, Any] | None = None

    async def load(self) -> bool:
        """Load the catalog: CDN, or a local file, or the bundled fallback.

        A local catalog built AFTER the CDN one wins. The CDN copy is only
        republished by nocode-ui's CI, so a developer who edits component
        properties and regenerates locally would otherwise keep validating
        against a catalog that predates their change and see their new property
        rejected as unknown. Comparing `generatedAt` gives the fresh build
        precedence without anyone having to set a flag; when the CDN copy is
        the newer of the two, nothing changes.

        Returns True when a real catalog loaded, False when it fell back.
        """
        if not self.catalog_url:
            # No CDN configured. A local build is still much better than the
            # 5-component stub, whose TextBox has zero properties — the agent
            # cannot see designType/colorScheme and hand-styles everything.
            if self._load_local(_resolve_local_catalog(self.local_path)):
                return True
            logger.info("No catalog URL configured, using fallback catalog")
            self._catalog = _FALLBACK_CATALOG
            return True

        # An explicit local path (or file:// URL) in the URL slot: use it as-is.
        explicit = self.catalog_url
        if explicit.startswith("file://"):
            explicit = explicit[len("file://"):]
        if not explicit.startswith(("http://", "https://")):
            if self._load_local(Path(explicit).expanduser()):
                return True
            self._catalog = _FALLBACK_CATALOG
            return False

        try:
            async with httpx.AsyncClient(timeout=10.0) as client:
                resp = await client.get(self.catalog_url)
                resp.raise_for_status()
                self._catalog = resp.json()
                component_count = len(self._catalog.get("components", {}))
                logger.info(
                    "Loaded component catalog: %s components from %s",
                    component_count, self.catalog_url,
                )
        except Exception as e:  # noqa: BLE001
            logger.warning("Failed to load catalog from CDN: %s. Trying local.", e)
            if self._load_local(_resolve_local_catalog(self.local_path)):
                return True
            self._catalog = _FALLBACK_CATALOG
            return False

        newer = self._newer_local_catalog()
        if newer is not None and self._load_local(newer):
            logger.info("Local catalog is newer than the CDN copy; preferring it.")
        return True

    def _load_local(self, path: Path | None) -> bool:
        """Read a catalog from disk into self._catalog. False on any problem."""
        if path is None:
            return False
        try:
            self._catalog = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as e:
            logger.warning("Failed to load catalog file %s: %s", path, e)
            return False
        count = len(self._catalog.get("components", {}))
        logger.info("Loaded component catalog: %s components from file %s", count, path)
        return True

    def _newer_local_catalog(self) -> Path | None:
        """A local catalog generated after the one just fetched, or None.

        Both sides stamp `generatedAt` as ISO-8601, which sorts correctly as
        text. A missing or unparseable stamp on either side means we cannot
        tell, so the CDN copy stays.
        """
        path = _resolve_local_catalog(self.local_path)
        if path is None:
            return None
        remote_stamp = (self._catalog or {}).get("generatedAt")
        if not isinstance(remote_stamp, str):
            return None
        try:
            local_stamp = json.loads(path.read_text(encoding="utf-8")).get("generatedAt")
        except (OSError, ValueError) as e:
            logger.warning("Local catalog at %s unreadable: %s", path, e)
            return None
        return path if isinstance(local_stamp, str) and local_stamp > remote_stamp else None

    def get_component_info(self, component_type: str) -> dict[str, Any]:
        """Get property definitions for a component type."""
        if not self._catalog:
            return {}
        return self._catalog.get("components", {}).get(component_type, {})

    def get_all_types(self) -> list[str]:
        """List all available component types."""
        if not self._catalog:
            return []
        return list(self._catalog.get("components", {}).keys())

    def to_prompt_context(self) -> str:
        """Format catalog as tier-aware text for system prompt injection.

        Tier-based output:
        - common/data: full detail (description, structure, properties,
          sub-components, design types)
        - specialized/table/multimedia: one-liner grouped by category
        - internal: omitted entirely

        Components without a tier field are treated as "specialized"
        (backwards-compatible with catalogs generated before tiers).
        """
        if not self._catalog:
            return ""

        components = self._catalog.get("components", {})
        if not components:
            return ""

        full_detail, condensed_groups = _partition_by_tier(components)

        all_visible = [n for n, _ in full_detail]
        for items in condensed_groups.values():
            all_visible.extend(n for n, _ in items)

        lines = ["## Component Catalog\n"]
        lines.append(f"Available types ({len(all_visible)}): {', '.join(all_visible)}\n")

        _append_design_type_reference(lines, self._catalog)

        for comp_type, info in full_detail:
            _format_component_full(lines, comp_type, info)

        for group_name, items in condensed_groups.items():
            if not items:
                continue
            lines.append(f"### {group_name}")
            for comp_type, info in items:
                desc = info.get("description", "")
                lines.append(f"- **{comp_type}**: {desc}" if desc else f"- **{comp_type}**")
            lines.append("")

        return "\n".join(lines)


# ── Module-level singleton ────────────────────────────────────────────────
#
# Tools that need catalog access (e.g. the modlix port's _conventions.py
# `is_multi_valued_property`) read through these accessors instead of
# threading the catalog through every call site. main.py's lifespan calls
# `set_catalog(catalog)` after `await catalog.load()`. Code that runs before
# the lifespan (unit tests, scripts) gets an empty catalog from get_catalog()
# and falls back to other heuristics — no crashes from a missing singleton.

_catalog_singleton: "ComponentCatalog | None" = None


def set_catalog(catalog: "ComponentCatalog") -> None:
    """Register the loaded catalog as the module-level singleton."""
    global _catalog_singleton
    _catalog_singleton = catalog


def get_catalog() -> "ComponentCatalog":
    """Return the registered catalog, or an empty one if not yet set.

    The empty-catalog fallback keeps `is_multi_valued_property` and other
    catalog-aware helpers usable in contexts where the lifespan hasn't run
    (tests, scripts). Catalog-aware lookups return empty dicts; callers
    degrade to their non-catalog heuristics.
    """
    global _catalog_singleton
    if _catalog_singleton is None:
        _catalog_singleton = ComponentCatalog("")
    return _catalog_singleton


# Tiers that get full detail in the prompt
_FULL_DETAIL_TIERS = {"common", "data"}

# Display names for condensed tier groups
_CONDENSED_GROUP_NAMES: dict[str, str] = {
    "specialized": "Specialized Components",
    "table": "Table Components",
    "multimedia": "Multimedia Components",
}


def _partition_by_tier(
    components: dict[str, Any],
) -> tuple[list[tuple[str, dict]], dict[str, list[tuple[str, dict]]]]:
    """Split components into full-detail list and condensed groups by tier."""
    full_detail: list[tuple[str, dict]] = []
    condensed: dict[str, list[tuple[str, dict]]] = {
        name: [] for name in _CONDENSED_GROUP_NAMES.values()
    }
    for comp_type in sorted(components):
        info = components[comp_type]
        tier = info.get("tier", "specialized")
        if tier == "internal":
            continue
        if tier in _FULL_DETAIL_TIERS:
            full_detail.append((comp_type, info))
        else:
            group_name = _CONDENSED_GROUP_NAMES.get(tier, "Specialized Components")
            condensed[group_name].append((comp_type, info))
    return full_detail, condensed


def _append_design_type_reference(lines: list[str], catalog: dict[str, Any]) -> None:
    """Append design-type descriptions to output lines."""
    dt_descs = catalog.get("designTypeDescriptions", {})
    if not dt_descs:
        return
    lines.append("### Design Type Reference")
    for dt_name, dt_desc in dt_descs.items():
        lines.append(f"- **{dt_name}**: {dt_desc}")
    lines.append("")


def _format_component_full(lines: list[str], comp_type: str, info: dict) -> None:
    """Append full-detail lines for a single component."""
    description = info.get("description", "")
    lines.append(f"### {comp_type}")
    if description:
        lines.append(description)

    structure = info.get("structure")
    if structure:
        lines.append(f"Structure: `{structure}`")

    _append_properties(lines, info.get("properties", []))
    _append_sub_components(lines, info.get("subComponents", {}))

    theme = info.get("themeStyleProperties", {})
    design_types = theme.get("designTypes", []) if theme else []
    if design_types:
        lines.append(f"Design types: {', '.join(design_types)}")

    lines.append("")


def _append_properties(lines: list[str], props: list[dict]) -> None:
    """Append property names and enum values to output lines."""
    if not props:
        return
    # A flat [:20] slice buried TextBox's shortcut props (indexes 38-43), so the
    # agent saw `shortcutAction: [...]` enums with no property name to attach them
    # to. Keep the cap for budget, but never let it drop a shortcut property.
    names = [p.get("name", "?") for p in props]
    head = names[:20]
    tail = [n for n in names[20:] if n.startswith("shortcut") or n == "onShortcut"]
    lines.append(f"Properties: {', '.join(head + tail)}")
    for p in props:
        enum_vals = p.get("enumValues", [])
        if enum_vals:
            names = [e.get("name", "?") for e in enum_vals]
            lines.append(f"  {p['name']}: {names}")


def _append_sub_components(lines: list[str], sub_comps: dict) -> None:
    """Append stylable sub-component parts to output lines."""
    if not sub_comps or len(sub_comps) <= 1:
        return
    parts = [
        f"{key} ({sub_info.get('description', key)})"
        for key, sub_info in sub_comps.items()
        if key != "(root)"
    ]
    if parts:
        lines.append(f"Stylable parts: {', '.join(parts)}")


